function validate_model(G)
%VALIDATE_MODEL Check all fields used by the canonical engine.
required = {'name','placeNames','transitionNames','Pre','Post','M0', ...
    'lower','upper','protectable','timeout','gamma','cost', ...
    'secretRequirement','nP','nT'};
for k = 1:numel(required)
    assert(isfield(G,required{k}), 'Missing model field: %s',required{k});
end
assert(isequal(size(G.Pre),[G.nP G.nT]),'Pre has the wrong size.');
assert(isequal(size(G.Post),[G.nP G.nT]),'Post has the wrong size.');
assert(numel(G.M0)==G.nP && all(G.M0>=0) && ...
    all(mod(G.M0,1)==0),'M0 must be a nonnegative integer vector.');
assert(all(G.Pre(:)>=0) && all(G.Post(:)>=0) && ...
    all(mod(G.Pre(:),1)==0) && all(mod(G.Post(:),1)==0), ...
    'Pre and Post must contain nonnegative integers.');
assert(numel(G.lower)==G.nT && numel(G.upper)==G.nT, ...
    'Every transition needs one firing interval.');
assert(all(G.lower>=0) && all(G.lower<G.upper), ...
    'Every interval must satisfy 0 <= lower < upper.');
assert(islogical(G.protectable) && numel(G.protectable)==G.nT, ...
    'protectable must be a logical vector of length nT.');
assert(numel(G.timeout)==G.nT && numel(G.gamma)==G.nT && ...
    numel(G.cost)==G.nT,'timeout, gamma, and cost must have length nT.');
assert(all(isfinite(G.timeout(G.protectable))) && ...
    all(G.timeout(G.protectable)>0), ...
    'Every protectable transition needs a positive finite timeout.');
assert(all(G.gamma(G.protectable)>=0) && all(G.cost(G.protectable)>=0), ...
    'gamma and cost must be nonnegative.');
assert(numel(G.placeNames)==G.nP && numel(G.transitionNames)==G.nT, ...
    'Place/transition names have the wrong lengths.');

hasExact=isfield(G,'secretMarkings');
hasPlace=isfield(G,'secretPlace');
assert(xor(hasExact,hasPlace), ...
    'Use exactly one secret representation: secretMarkings or secretPlace.');
if hasExact
    assert(size(G.secretMarkings,1)==G.nP, ...
        'Secret markings must be stored as columns.');
    assert(size(G.secretMarkings,2)==numel(G.secretRequirement), ...
        'Each secret marking needs one requirement.');
    assert(all(G.secretRequirement>=0), ...
        'Secret requirements must be nonnegative.');
else
    assert(isscalar(G.secretPlace) && G.secretPlace>=1 && ...
        G.secretPlace<=G.nP && mod(G.secretPlace,1)==0, ...
        'secretPlace must be a valid place index.');
    assert(isscalar(G.secretRequirement) && G.secretRequirement>=0, ...
        'A secretPlace model needs one nonnegative secretRequirement.');
    if isfield(G,'secretMinimumTokens')
        assert(isscalar(G.secretMinimumTokens) && ...
            G.secretMinimumTokens>=1 && mod(G.secretMinimumTokens,1)==0, ...
            'secretMinimumTokens must be a positive integer.');
    end
end
end
